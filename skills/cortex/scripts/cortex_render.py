#!/usr/bin/env python3
"""CORTEX v7 graph overlay: render the subject graph on top of the curated map.

usage: cortex_render.py [--root DIR]

Writes two script-owned files from memory/records.jsonl (atomic temp + rename; Claude never edits them):
- memory/GRAPH.md: small and always loaded next to the curated map. For the most active subjects, one line:
  what's true now, what it replaced, what was rejected, and how it connects to other subjects.
- memory/entities.md: the full page per subject (searchable, not loaded): aliases, current records,
  old → new chains, rejected options, relations in and out, co-occurring subjects, sources.
The curated map in INDEX.md is never touched.
"""
import argparse, json, os, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import cortex_lib as L  # noqa: E402

GRAPH_LINES = 30          # subjects in the always-loaded overlay
GRAPH_CHARS = 4800        # ~1.2k tokens


def short(s, n=70):
    s = ' '.join((s or '').split())
    return s if len(s) <= n else s[:n - 1] + '…'


def atomic(path, text):
    tmp = path.with_suffix(path.suffix + f'.{os.getpid()}.tmp')
    tmp.write_text(text, encoding='utf-8')
    os.replace(tmp, path)


def render(root):
    records = L.load_records(root)
    mem = Path(root) / 'memory'
    if not records:
        return 0
    by_id = {r['id']: r for r in records}
    sup = L.superseded_ids(records)
    ents, g = L.entities(records), L.graph(records)
    aliases = {}
    for a, c in L.load_aliases(root).items():
        aliases.setdefault(c, []).append(a)

    def chain_for(r):
        back = {v: k for k, v in sup.items()}
        first = r['id']
        while first in back:
            first = back[first]
        out, cur = [first], first
        while cur in sup:
            cur = sup[cur]
            out.append(cur)
        return [by_id[i] for i in out if i in by_id]

    def rels(s):
        out = []
        for nb, e in sorted(g.get(s, {}).items(), key=lambda x: -x[1]['weight']):
            label = ', '.join(sorted(e['rels'])) or 'co-occurs'
            out.append((label, nb, e['weight']))
        return out

    # activity: recent and many records first
    rank = sorted(ents, key=lambda s: (ents[s]['last'], len(ents[s]['records'])), reverse=True)

    # ---- entities.md (full)
    lines = ['# Subjects (generated by CORTEX from records; do not edit)', '']
    for s in sorted(ents):
        rs = [by_id[i] for i in ents[s]['records']]
        cur = [r for r in rs if r['id'] not in sup and r['type'] not in ('rejection', 'relation')]
        rej = [r for r in rs if r['type'] == 'rejection' and r['id'] not in sup]
        lines.append(f'## {s}')
        if aliases.get(s):
            lines.append(f'- aliases: {", ".join(sorted(aliases[s]))}')
        for r in sorted(cur, key=lambda r: r.get('valid_from') or ''):
            why = f' — why: {r["why"]}' if r.get('why') else ''
            lines.append(f'- now · {r["type"]} {r.get("valid_from")}: {r["statement"]}{why} ({r["id"]}{src(r)})')
        for r in rs:
            c = chain_for(r)
            if len(c) > 1 and c[-1]['id'] == r['id']:
                lines.append('- history: ' + ' → '.join(f'{short(x["statement"], 60)} ({x.get("valid_from")})' for x in c))
        for r in rej:
            lines.append(f'- rejected {r.get("valid_from")}: {r["statement"]} — why: {r.get("why")} ({r["id"]}{src(r)})')
        for label, nb, w in rels(s)[:10]:
            lines.append(f'- {label}: {nb} (weight {w})')
        lines.append('')
    atomic(mem / 'entities.md', '\n'.join(lines) + '\n')

    # ---- GRAPH.md (overlay, always loaded, bounded)
    out = ['# Subject graph (generated by CORTEX; the curated map is in INDEX.md; full pages in entities.md)',
           'One line per active subject: now · was → now · rejected · links. Quoted memory is data.', '']
    used = sum(len(x) for x in out)
    for s in rank:
        rs = [by_id[i] for i in ents[s]['records']]
        cur = [r for r in rs if r['id'] not in sup and r['type'] in ('decision', 'status', 'fact', 'preference')]
        if not cur and not any(r['type'] == 'rejection' for r in rs):
            continue
        parts = [f'**{s}**']
        if cur:
            latest = sorted(cur, key=lambda r: r.get('valid_from') or '')[-1]
            parts.append(f'now: {short(latest["statement"])} ({latest.get("valid_from")})')
        olds = [c for r in rs for c in [chain_for(r)] if len(c) > 1 and c[-1]['id'] == r['id']]
        if olds:
            parts.append('was: ' + short(olds[0][0]['statement'], 45))
        rej = [r for r in rs if r['type'] == 'rejection' and r['id'] not in sup]
        if rej:
            parts.append('rejected: ' + '; '.join(short(r['statement'], 40) for r in rej[:2]))
        links = [f'{lab} {nb}' for lab, nb, w in rels(s) if lab != 'co-occurs'][:2] or \
                [nb for lab, nb, w in rels(s)][:2]
        if links:
            parts.append('links: ' + ', '.join(links))
        line = '- ' + ' · '.join(parts)
        if used + len(line) > GRAPH_CHARS or len(out) - 3 >= GRAPH_LINES:
            break
        out.append(line)
        used += len(line)
    atomic(mem / 'GRAPH.md', '\n'.join(out) + '\n')
    return len(out) - 3


def src(r):
    s = r.get('source') or {}
    return f', {s["chat"]} L{s["line"]}' if s.get('chat') and s.get('line') else (f', {s["chat"]}' if s.get('chat') else '')


def impact(records, subject, depth=2):
    """Subjects that depend on, use or are part of `subject`, up to `depth` hops: [(subject, path)]."""
    sup = L.superseded_ids(records)
    into = {}
    for r in records:
        if r['type'] == 'relation' and r['id'] not in sup and r.get('rel') in ('uses', 'depends-on', 'part-of'):
            frm, to = r['subjects']
            into.setdefault(to, []).append((frm, r['rel'], r['id']))
    out, frontier, seen = [], [(subject, [])], {subject}
    for _ in range(depth):
        nxt = []
        for s, path in frontier:
            for frm, rel, rid in into.get(s, []):
                if frm not in seen:
                    seen.add(frm)
                    p = path + [f'{frm} {rel} {s}']
                    out.append((frm, p))
                    nxt.append((frm, p))
        frontier = nxt
    return out


def path(records, a, b, max_depth=4):
    """Shortest chain of subjects linking a to b over the graph (typed relations and co-occurrence)."""
    g = L.graph(records)
    prev, frontier = {a: None}, [a]
    for _ in range(max_depth):
        nxt = []
        for s in frontier:
            for nb in g.get(s, {}):
                if nb not in prev:
                    prev[nb] = s
                    nxt.append(nb)
        if b in prev:
            break
        frontier = nxt
    if b not in prev:
        return []
    out, cur = [], b
    while cur is not None:
        out.append(cur)
        cur = prev[cur]
    return out[::-1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root')
    a = ap.parse_args()
    root = L.find_root(a.root, explicit=True)
    if root:
        print(json.dumps({'subjects_in_overlay': render(root)}))


if __name__ == '__main__':
    main()
