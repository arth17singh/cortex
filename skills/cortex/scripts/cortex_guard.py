#!/usr/bin/env python3
"""CORTEX v7 write guard: PreToolUse and PostToolUse hooks that turn the memory-writing rules into code.

PreToolUse (Edit|Write|MultiEdit|Bash|Read|Grep|Glob):
- denies edits to script-owned files (records.jsonl, entities.md, aliases.json, sessions/README.md,
  */_index.md, *.records.md), with the right command in the reason;
- adds a source tag `(<id8> L<n>)` to new topic-file bullets that lack one, and a `(L<a>-<b>)` range to new
  session-log exchange headings, by rewriting the tool input on the way in (`updatedInput`);
- appends `--session <id> --line <n>` to cortex_write.py calls, so provenance is never typed by hand;
- denies shell writes to script-owned files, and every memory access while CORTEX is off.
PostToolUse (Edit|Write|MultiEdit): lints the write that just happened (a session log over 300 lines, a
`Rejected:` bullet with no matching record) and tells Claude exactly what to run. The turn continues.

Silent and exit 0 outside CORTEX projects, inside nested CORTEX calls (CORTEX_NESTED), or on any error.
"""
import json, os, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

SCRIPT_OWNED = re.compile(r'(^|/)memory/(records\.jsonl|entities\.md|aliases\.json|sessions/README\.md|'
                          r'[^/]+/_index\.md|[^/]+/[^/]+\.records\.md)$')
TAG = re.compile(r'\((?:auto )?[0-9a-f]{8}(?: L[\d-]+)?\)|\(code: [^)]+\)|\(r-[0-9a-f]{6}\)')
RANGE = re.compile(r'\(L\d+-\d+\)\s*$')
NOT_TOPIC = {'sessions', 'log', '_templates', 'team', '.backups'}
SHELL_WRITE = re.compile(r'(>>?|\btee\b|\bsed\s+-i|\bcp\b|\bmv\b|\brm\b|\btruncate\b)[^|;&]*memory/'
                         r'(records\.jsonl|entities\.md|aliases\.json|sessions/README\.md|[^/\s]+/_index\.md|'
                         r'[^/\s]+/[^/\s]+\.records\.md)')


def count_lines(p):
    try:
        with open(p, 'rb') as f:
            return sum(chunk.count(b'\n') for chunk in iter(lambda: f.read(1 << 20), b''))
    except OSError:
        return 0


def rel_memory(root, path):
    """'memory/…' relative path if `path` is inside this project's memory folder, else None."""
    try:
        r = Path(path).resolve().relative_to(Path(root).resolve())
    except (ValueError, OSError):
        return None
    s = r.as_posix()
    return s if s.startswith('memory/') else None


def kind(rel):
    if SCRIPT_OWNED.search(rel):
        return 'script'
    parts = rel.split('/')
    if len(parts) == 3 and parts[1] == 'sessions':
        return 'log'
    if len(parts) == 3 and parts[1] not in NOT_TOPIC and parts[2].endswith('.md'):
        return 'topic'
    return 'other'


def tag_bullets(text, tag):
    """Append `tag` to bullet lines that carry no source tag yet (skips headers like Summary/Last updated)."""
    out, fence = [], False
    for line in text.split('\n'):
        if line.strip().startswith('```'):
            fence = not fence
        s = line.strip()
        if (not fence and s.startswith('- ') and len(s) > 12 and not TAG.search(s)
                and not re.match(r'-\s*(summary|last updated|related)\b', s, re.I)):
            line = line.rstrip() + f' {tag}'
        out.append(line)
    return '\n'.join(out)


def range_headings(text, existing, upto):
    """Give new `### …` exchange headings without a range `(L<a>-<upto>)`, continuing after the log's last range."""
    last = max([int(b) for b in re.findall(r'\(L\d+-(\d+)\)', existing)] or [0])
    start = min(last + 1, upto)
    out = []
    for line in text.split('\n'):
        if line.startswith('### ') and not RANGE.search(line) and upto:
            line = line.rstrip() + f' (L{start}-{upto})'
        out.append(line)
    return '\n'.join(out)


def deny(reason):
    print(json.dumps({'hookSpecificOutput': {'hookEventName': 'PreToolUse', 'permissionDecision': 'deny',
                                             'permissionDecisionReason': reason}}))


def rewrite(tool_input):
    print(json.dumps({'hookSpecificOutput': {'hookEventName': 'PreToolUse', 'updatedInput': tool_input}}))


def pre(data, root, switch):
    tool, inp = data.get('tool_name', ''), dict(data.get('tool_input') or {})
    sid = (data.get('session_id') or '')[:8]
    n = count_lines(data.get('transcript_path') or '')
    write_cmd = f'python3 {HERE / "cortex_write.py"} --type … --subject … --statement … --why …'

    if tool == 'Bash':
        cmd = inp.get('command', '')
        if switch == 'off' and 'memory/' in cmd:
            return deny('CORTEX is off for this chat or project: leave memory/ alone (/cortex on turns it back on).')
        if SHELL_WRITE.search(cmd):
            return deny('That file in memory/ is script-owned. Records go through cortex_write.py '
                        f'({write_cmd}); maps and indexes are regenerated by CORTEX.')
        if 'cortex_write.py' in cmd and '--session' not in cmd and sid:
            inp['command'] = re.sub(r'(cortex_write\.py)', rf'\1 --session {data.get("session_id")} --line {n}', cmd, count=1)
            return rewrite(inp)
        return None

    path = inp.get('file_path') or inp.get('path') or ''
    rel = rel_memory(root, path) if path else None
    if tool in ('Read', 'Grep', 'Glob'):
        if switch == 'off' and (rel or 'memory' in str(inp.get('path') or inp.get('pattern') or '')):
            return deny('CORTEX is off for this chat or project: answer without memory (/cortex on turns it back on).')
        return None
    if not rel or tool not in ('Edit', 'Write', 'MultiEdit'):
        return None
    if switch == 'off':
        return deny('CORTEX is off: nothing is saved to memory (/cortex on turns it back on).')
    k = kind(rel)
    if k == 'script':
        return deny(f'{rel} is script-owned and regenerated by CORTEX; don\'t edit it. Record decisions, rejections and '
                    f'facts with: {write_cmd}')
    if k not in ('topic', 'log') or not sid:
        return None
    existing = Path(path).read_text(encoding='utf-8', errors='replace') if Path(path).is_file() else ''
    fix = (lambda t: tag_bullets(t, f'({sid} L{n})')) if k == 'topic' else (lambda t: range_headings(t, existing, n))
    changed = False
    for field in ('new_string', 'content'):
        if isinstance(inp.get(field), str):
            new = fix(inp[field])
            changed |= new != inp[field]
            inp[field] = new
    if isinstance(inp.get('edits'), list):
        edits = []
        for e in inp['edits']:
            e = dict(e)
            if isinstance(e.get('new_string'), str):
                new = fix(e['new_string'])
                changed |= new != e['new_string']
                e['new_string'] = new
            edits.append(e)
        inp['edits'] = edits
    return rewrite(inp) if changed else None


def post(data, root):
    tool, inp = data.get('tool_name', ''), data.get('tool_input') or {}
    path = inp.get('file_path') or ''
    rel = rel_memory(root, path) if path else None
    if not rel or tool not in ('Edit', 'Write', 'MultiEdit'):
        return None
    k, notes = kind(rel), []
    if k == 'log' and count_lines(path) > 300:
        notes.append(f'{rel} is over 300 lines: continue in a new part ({Path(path).stem}-p2.md) and add its line to the map.')
    if k in ('topic', 'log'):
        import cortex_lib as L
        written = '\n'.join(str(x) for x in (inp.get('new_string'), inp.get('content')) if x)
        written += '\n'.join(str(e.get('new_string', '')) for e in inp.get('edits') or [] if isinstance(e, dict))
        recs = [r['statement'] for r in L.load_records(root) if r['type'] == 'rejection']
        for m in re.finditer(r'^\s*-\s*\**Rejected:?\**\s*(.+)$', written, re.M | re.I):
            text = TAG.sub('', m.group(1)).strip()
            if text and not any(L.overlap(text, s) >= .35 for s in recs):
                notes.append(f'Rejected option written without a record: "{text[:80]}". Record it: python3 '
                             f'{HERE / "cortex_write.py"} --type rejection --subject <subject> --statement "…" --why "…"')
    if notes:
        print(json.dumps({'decision': 'block', 'reason': 'CORTEX: ' + ' '.join(notes[:3])}))
    return None


def main():
    if os.environ.get('CORTEX_NESTED'):
        return
    try:
        data = json.loads(sys.stdin.read() or '{}')
        import cortex_lib as L
        root = L.find_root(data.get('cwd'))
        if not root or not (root / 'memory' / 'LEDGER.md').is_file():
            return
        try:
            import cortex_hook as H
            switch = H.memory_switch(root, data.get('session_id') or '')[0]
        except Exception:
            switch = None
        event = data.get('hook_event_name')
        if event == 'PreToolUse':
            pre(data, root, switch)
        elif event == 'PostToolUse':
            post(data, root)
    except Exception:
        pass


if __name__ == '__main__':
    main()
    sys.exit(0)
